"""Sensor data pipeline for TrustMesh.

Generates synthetic industrial-style sensor telemetry and provides
robust schema and data validation.
All readings generated by this module are synthetic demo data.
"""

from typing import Union
import io
import numpy as np
import pandas as pd

# The six core industrial sensors modeled for the TrustMesh prototype
REQUIRED_SENSORS = [
    "FIT101",  # Primary Inflow Transmitter (m3/h)
    "LIT101",  # Primary Tank Level Transmitter (mm)
    "AIT202",  # Chemical Water Quality / pH Transmitter
    "FIT301",  # Secondary Process Transfer Flow (m3/h)
    "LIT301",  # Secondary Tank Level Transmitter (mm)
    "AIT401",  # Effluent Turbidity / Conductivity Analyzer
]

REQUIRED_COLUMNS = ["Timestamp"] + REQUIRED_SENSORS


def generate_synthetic_sensor_data(
    n_samples: int = 500,
    seed: int = 42,
    start_time: str = "2026-03-01 08:00:00",
    freq_seconds: int = 2,
) -> pd.DataFrame:
    """Generate reproducible, correlated synthetic industrial sensor telemetry.

    Notice: All returned readings are synthetic demo data.

    Args:
        n_samples: Number of chronological samples to generate (default 500).
        seed: Fixed random seed for deterministic reproducibility.
        start_time: Base starting timestamp for the telemetry stream.
        freq_seconds: Sampling frequency interval in seconds.

    Returns:
        pd.DataFrame containing Timestamp and the 6 required sensor columns.
    """
    rng = np.random.default_rng(seed)

    timestamps = pd.date_range(
        start=start_time,
        periods=n_samples,
        freq=f"{freq_seconds}s",
    )

    t = np.linspace(0, 10 * np.pi, n_samples)

    # 1. FIT101: Inflow rate oscillating around nominal 2.5 m3/h with pump cycles
    fit101_base = 2.5 + 0.35 * np.sin(t * 0.4)
    fit101_noise = rng.normal(0, 0.02, size=n_samples)
    fit101 = np.clip(fit101_base + fit101_noise, 0.5, 4.0)

    # 2. LIT101: Tank level (mm), physically coupled to cumulative inflow and discharge
    # Primary level has a baseline around 750 mm, responding smoothly with phase lag to FIT101
    lit101_base = 750.0 + 35.0 * np.sin(t * 0.4 - 0.7) + 15.0 * np.cos(t * 0.15)
    lit101_noise = rng.normal(0, 0.6, size=n_samples)
    lit101 = np.clip(lit101_base + lit101_noise, 300.0, 1000.0)

    # 3. AIT202: Chemical pH analyzer centered at 7.20 with slow buffering kinetics
    ait202_base = 7.20 + 0.12 * np.cos(t * 0.25)
    ait202_noise = rng.normal(0, 0.015, size=n_samples)
    ait202 = np.clip(ait202_base + ait202_noise, 5.5, 9.0)

    # 4. FIT301: Outflow / transfer flow rate (m3/h), correlated with tank head/LIT101
    fit301_base = 2.2 + 0.25 * np.sin(t * 0.4 - 0.5)
    fit301_noise = rng.normal(0, 0.02, size=n_samples)
    fit301 = np.clip(fit301_base + fit301_noise, 0.4, 3.8)

    # 5. LIT301: Secondary buffer tank level (mm), oscillating around nominal 820 mm
    lit301_base = 820.0 + 28.0 * np.sin(t * 0.35 - 1.2)
    lit301_noise = rng.normal(0, 0.7, size=n_samples)
    lit301 = np.clip(lit301_base + lit301_noise, 400.0, 1100.0)

    # 6. AIT401: Secondary conductivity / turbidity transmitter (ppm)
    ait401_base = 250.0 + 12.0 * np.sin(t * 0.3) + 6.0 * np.cos(t * 0.6)
    ait401_noise = rng.normal(0, 0.8, size=n_samples)
    ait401 = np.clip(ait401_base + ait401_noise, 150.0, 380.0)

    df = pd.DataFrame(
        {
            "Timestamp": timestamps,
            "FIT101": np.round(fit101, 3),
            "LIT101": np.round(lit101, 2),
            "AIT202": np.round(ait202, 3),
            "FIT301": np.round(fit301, 3),
            "LIT301": np.round(lit301, 2),
            "AIT401": np.round(ait401, 2),
        }
    )

    validate_sensor_data(df)
    return df


def validate_sensor_data(df: pd.DataFrame) -> bool:
    """Validate that the DataFrame satisfies schema, timestamp, and numeric requirements.

    Args:
        df: pd.DataFrame to validate.

    Returns:
        True if the DataFrame passes validation.

    Raises:
        ValueError: If required columns are missing, data is empty, timestamps are
            invalid/non-monotonic, or sensor columns are non-numeric.
    """
    if not isinstance(df, pd.DataFrame):
        raise ValueError(f"Input must be a pandas DataFrame, got {type(df).__name__}.")

    if df.empty:
        raise ValueError("DataFrame is empty.")

    # 1. Check required columns
    missing_cols = [col for col in REQUIRED_COLUMNS if col not in df.columns]
    if missing_cols:
        raise ValueError(
            f"Missing required sensor columns: {missing_cols}. "
            f"Expected all of: {REQUIRED_COLUMNS}"
        )

    # 2. Check and validate Timestamp
    timestamps = pd.to_datetime(df["Timestamp"], errors="coerce")
    if timestamps.isna().any():
        nan_count = int(timestamps.isna().sum())
        raise ValueError(
            f"Timestamp column contains {nan_count} invalid or unparseable datetime values."
        )

    if not timestamps.is_monotonic_increasing:
        raise ValueError("Timestamp values must be monotonically increasing.")

    # 3. Check numeric data types for sensor columns
    for sensor in REQUIRED_SENSORS:
        # Note: missing data injection may introduce NaNs, which is permitted in numeric float columns.
        if not pd.api.types.is_numeric_dtype(df[sensor]):
            raise ValueError(
                f"Column '{sensor}' must contain numeric data, found type '{df[sensor].dtype}'."
            )

    return True


def load_sensor_csv(filepath_or_buffer: Union[str, io.StringIO, io.BytesIO]) -> pd.DataFrame:
    """Load and validate user-supplied CSV telemetry.

    Args:
        filepath_or_buffer: File path, string buffer, or file-like object.

    Returns:
        Validated pd.DataFrame with parsed timestamps and numeric sensor readings.

    Raises:
        ValueError: If CSV fails schema or data validation.
    """
    try:
        df = pd.read_csv(filepath_or_buffer)
    except Exception as e:
        raise ValueError(f"Failed to read CSV input: {e}") from e

    if not isinstance(df, pd.DataFrame) or df.empty:
        raise ValueError("Uploaded CSV is empty or contains no records.")

    missing_cols = [col for col in REQUIRED_COLUMNS if col not in df.columns]
    if missing_cols:
        raise ValueError(
            f"Missing required sensor columns: {missing_cols}. "
            f"Expected all of: {REQUIRED_COLUMNS}"
        )

    df["Timestamp"] = pd.to_datetime(df["Timestamp"], errors="coerce")

    # Validate against schema and requirements
    validate_sensor_data(df)

    # Ensure clean numeric types
    for sensor in REQUIRED_SENSORS:
        df[sensor] = pd.to_numeric(df[sensor])

    return df
